"""P2 load: UNSW-NB15 (4 headerless CSV parts) -> SQLite.

Steps
  1. Load the definition file into feature_def and derive the flow table from it.
  2. Stream each part in chunks; map IPs / protocol / service / state to dimension ids.
  3. Clean known defects: hex or '-' port values, attack labels with stray spaces
     and the Backdoor/Backdoors split, blank Label for some normal rows.
  4. Build indexes after the bulk insert.

Usage: python3 src/load.py
"""
import re
import sqlite3
import time
from collections import Counter
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
PARTS = [DATA / f"UNSW-NB15_{i}.csv" for i in range(1, 5)]
FEATURES = DATA / "NUSW-NB15_features.csv"
DB = Path.home() / "Library/CloudStorage/GoogleDrive-kwooler@gmail.com/My Drive/Sqlite/SCCUR26-P2.db"
CHUNK = 500_000

SQL_TYPE = {"nominal": "TEXT", "integer": "INTEGER", "float": "REAL",
            "timestamp": "INTEGER", "binary": "INTEGER"}
# Raw columns replaced by a foreign key (or parsed separately) in the flow table.
DIMENSION_COLS = {"srcip", "dstip", "proto", "state", "service", "attack_cat", "label", "sport", "dsport"}
CANONICAL_ATTACK = {"Backdoor": "Backdoors"}


def clean_name(raw):
    return re.sub(r"\s+", "", raw).lower()


def parse_port(v):
    """'80' -> 80, '0xcc09' -> 52233, '-' / '' -> None."""
    if not isinstance(v, str):
        return None
    v = v.strip()
    try:
        return int(v, 0)
    except ValueError:
        return None


class Dim:
    def __init__(self, con, table, col):
        self.con, self.table, self.col, self.ids = con, table, col, {}

    def get(self, value):
        if not isinstance(value, str):
            return None
        if value not in self.ids:
            cur = self.con.execute(f"INSERT INTO {self.table} ({self.col}) VALUES (?)", (value,))
            self.ids[value] = cur.lastrowid
        return self.ids[value]


def main():
    t0 = time.time()
    if DB.exists():
        DB.unlink()
    con = sqlite3.connect(DB)
    con.execute("PRAGMA foreign_keys = ON")
    con.execute("PRAGMA journal_mode = OFF")
    con.execute("PRAGMA synchronous = OFF")
    con.executescript((ROOT / "src" / "schema.sql").read_text())

    # 1. definition file -> feature_def -> generated flow DDL
    fdef = pd.read_csv(FEATURES, encoding="latin-1")
    fdef.columns = [c.strip() for c in fdef.columns]
    fdef["name"] = fdef["Name"].map(clean_name)
    fdef["type"] = fdef["Type"].str.strip().str.lower()
    con.executemany("INSERT INTO feature_def VALUES (?, ?, ?, ?, ?)",
                    zip(fdef["No."], fdef["name"], fdef["Name"], fdef["Type"].str.strip(), fdef["Description"]))
    names = fdef["name"].tolist()
    measures = [(n, SQL_TYPE[t]) for n, t in zip(fdef["name"], fdef["type"]) if n not in DIMENSION_COLS]

    ddl = ("CREATE TABLE flow (\n"
           "    flow_id       INTEGER PRIMARY KEY,\n"
           "    source_part   INTEGER NOT NULL,\n"
           "    src_host_id   INTEGER NOT NULL REFERENCES host(host_id),\n"
           "    sport         INTEGER,\n"
           "    dst_host_id   INTEGER NOT NULL REFERENCES host(host_id),\n"
           "    dsport        INTEGER,\n"
           "    protocol_id   INTEGER NOT NULL REFERENCES protocol(protocol_id),\n"
           "    state_id      INTEGER REFERENCES conn_state(state_id),\n"
           "    service_id    INTEGER REFERENCES service(service_id),\n"
           "    attack_cat_id INTEGER REFERENCES attack_category(attack_cat_id),\n"
           "    label         INTEGER NOT NULL CHECK (label IN (0, 1)),\n"
           + ",\n".join(f"    {n:<17} {t}" for n, t in measures) + "\n);\n")
    con.executescript(ddl)
    (ROOT / "src" / "schema_generated.sql").write_text(
        "-- Generated by load.py from NUSW-NB15_features.csv. Do not edit by hand.\n" + ddl)

    host = Dim(con, "host", "ip")
    proto = Dim(con, "protocol", "name")
    service = Dim(con, "service", "name")
    state = Dim(con, "conn_state", "name")
    attack = Dim(con, "attack_category", "name")
    variants = Counter()
    stats = Counter()

    insert_cols = ["source_part", "src_host_id", "sport", "dst_host_id", "dsport", "protocol_id",
                   "state_id", "service_id", "attack_cat_id", "label"] + [n for n, _ in measures]
    insert_sql = f"INSERT INTO flow ({', '.join(insert_cols)}) VALUES ({', '.join('?' * len(insert_cols))})"

    # 2-3. stream the parts
    for part_no, path in enumerate(PARTS, start=1):
        for chunk in pd.read_csv(path, header=None, names=names, dtype=str, encoding="utf-8-sig",
                                 chunksize=CHUNK, keep_default_na=False, na_values=[""]):
            stats[f"rows_part{part_no}"] += len(chunk)
            raw_label = chunk["attack_cat"]
            variants.update(raw_label.dropna().tolist())
            canon = raw_label.str.strip().replace(CANONICAL_ATTACK)

            sport = chunk["sport"].map(parse_port)
            dsport = chunk["dsport"].map(parse_port)
            stats["port_unparsed"] += int((sport.isna() & chunk["sport"].notna()).sum()
                                          + (dsport.isna() & chunk["dsport"].notna()).sum())

            # Label: 1 when an attack family is present, else the raw value, else 0.
            label = pd.to_numeric(chunk["label"], errors="coerce")
            stats["label_blank"] += int(label.isna().sum())
            label = label.fillna(canon.notna().astype(int)).astype(int)
            stats["label_attack_mismatch"] += int(((label == 1) != canon.notna()).sum())

            frame = pd.DataFrame({
                "source_part": part_no,
                "src_host_id": [host.get(x) for x in chunk["srcip"]],
                "sport": sport,
                "dst_host_id": [host.get(x) for x in chunk["dstip"]],
                "dsport": dsport,
                "protocol_id": [proto.get(x) for x in chunk["proto"]],
                "state_id": [state.get(x) for x in chunk["state"]],
                "service_id": [service.get(x) for x in chunk["service"]],
                "attack_cat_id": [attack.get(x) if isinstance(x, str) else None for x in canon],
                "label": label,
            })
            for n, t in measures:
                raw = chunk[n].str.strip()
                num = pd.to_numeric(raw, errors="coerce")
                bad = int((num.isna() & raw.notna() & (raw != "")).sum())
                if bad:
                    stats[f"non_numeric_{n}"] += bad
                frame[n] = num
            frame = frame.astype(object).where(frame.notna(), None)
            con.executemany(insert_sql, frame.itertuples(index=False, name=None))
            con.commit()
            print(f"  part {part_no}: {stats[f'rows_part{part_no}']:,} rows", flush=True)

    for raw, n in variants.items():
        canon = CANONICAL_ATTACK.get(raw.strip(), raw.strip())
        con.execute("INSERT INTO attack_label_variant VALUES (?, ?, ?)", (raw, attack.ids[canon], n))

    # 4. indexes after the bulk load
    con.executescript("""
        CREATE INDEX idx_flow_label   ON flow(label);
        CREATE INDEX idx_flow_attack  ON flow(attack_cat_id);
        CREATE INDEX idx_flow_service ON flow(service_id);
        CREATE INDEX idx_flow_src     ON flow(src_host_id);
        CREATE INDEX idx_flow_stime   ON flow(stime);
    """)
    con.commit()

    stats["total_rows"] = sum(v for k, v in stats.items() if k.startswith("rows_part"))
    stats["hosts"] = len(host.ids)
    stats["protocols"] = len(proto.ids)
    stats["services"] = len(service.ids)
    stats["states"] = len(state.ids)
    stats["attack_label_spellings"] = len(variants)
    stats["attack_categories"] = len(attack.ids)
    con.close()
    report = "\n".join(f"{k}: {v:,}" for k, v in sorted(stats.items()))
    report += f"\nseconds: {round(time.time() - t0, 1)}"
    (ROOT / "output" / "load_log.txt").write_text(f"DB: {DB}\n{report}\n")
    print(report)


if __name__ == "__main__":
    main()
